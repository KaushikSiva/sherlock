_conn = None
_conn_lock = threading.Lock()


def conn():
    global _conn
    with _conn_lock:
        if _conn is None or _conn.is_closed():
            _conn = connect()
        return _conn


def auth_header():
    # One Snowflake session authenticates everything: Cortex (Claude) and the managed MCP server.
    return {"Authorization": f'Snowflake Token="{conn().rest.token}"'}


def claude():
    # Cortex exposes an Anthropic-compatible Messages API.
    return anthropic.Anthropic(
        base_url=f"https://{conn().host}/api/v2/cortex",
        api_key="unused",
        default_headers=auth_header(),
        max_retries=2,
    )


class SnowflakeMCP:
    """Minimal MCP client (tools/list, tools/call) for a Snowflake-managed MCP server."""

    def __init__(self, fqn):
        db, schema, name = fqn.split(".")
        self.path = f"/api/v2/databases/{db}/schemas/{schema}/mcp-servers/{name}"
        self._id = 0

    def _rpc(self, method, params):
        self._id += 1
        r = requests.post(
            f"https://{conn().host}{self.path}",
            headers={**auth_header(), "Content-Type": "application/json", "Accept": "application/json, text/event-stream"},
            json={"jsonrpc": "2.0", "id": self._id, "method": method, "params": params},
            timeout=600,
        )
        r.raise_for_status()
        if r.headers.get("content-type", "").startswith("text/event-stream"):
            msgs = [
                json.loads(line[5:])
                for line in r.text.splitlines()
                if line.startswith("data:") and line[5:].strip() not in ("", "[DONE]")
            ]
            msg = next((m for m in reversed(msgs) if "result" in m or "error" in m), {})
        else:
            msg = r.json()
        if "error" in msg:
            raise RuntimeError(msg["error"].get("message", str(msg["error"])))
        return msg.get("result", {})

    def list_tools(self):
        return self._rpc("tools/list", {}).get("tools", [])

    def call(self, name, arguments):
        """Returns (text, is_error)."""
        result = self._rpc("tools/call", {"name": name, "arguments": arguments})
        text = "\n".join(c.get("text", "") for c in result.get("content", []) if c.get("type") == "text")
        if not text and "results" in result:
            text = json.dumps(result["results"])
        return text, bool(result.get("isError"))


