_mcp: dict[str, SnowflakeMCP] = {}


def mcp_for(dataset):
    if dataset not in _mcp:
        _mcp[dataset] = SnowflakeMCP(DATASETS[dataset]["mcp_server"])
    return _mcp[dataset]


def _cast(value, col):
    if value is None:
        return None
    t = col.get("type")
    if t == "fixed":
        return int(value) if not col.get("scale") else float(value)
    if t == "real":
        return float(value)
    if t == "boolean":
        return str(value).lower() == "true"
    return value


def parse_result_set(text):
    """sql_exec returns a Snowflake SQL API result set; turn it into columns, row dicts and the query id."""
    payload = json.loads(text)
    rs = payload["result_set"]
    meta = rs["resultSetMetaData"]["rowType"]
    cols = [c["name"] for c in meta]
    rows = [{c["name"]: _cast(v, c) for v, c in zip(row, meta)} for row in rs.get("data", [])[:MAX_ROWS]]
    return cols, rows, payload.get("query_id")


def schema_context(dataset):
    scope, semantic_view = DATASETS[dataset]["scope"], DATASETS[dataset]["semantic_view"]
    db, schema = scope.split(".")
    cur = conn().cursor()
    cur.execute(
        f"""SELECT table_name, LISTAGG(column_name || ' ' || data_type, ', ') WITHIN GROUP (ORDER BY ordinal_position)
            FROM {db}.INFORMATION_SCHEMA.COLUMNS WHERE table_schema = %s GROUP BY 1 ORDER BY 1""",
        (schema,),
    )
    tables = "\n".join(f"- {scope}.{t}({cols})" for t, cols in cur.fetchall())
    semantic = ""
    if semantic_view:
        try:
            cur.execute("SELECT GET_DDL('SEMANTIC_VIEW', %s)", (semantic_view,))
            semantic = cur.fetchone()[0]
        except Exception:
            pass
    return tables, semantic


